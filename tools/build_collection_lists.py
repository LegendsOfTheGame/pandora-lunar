"""Builds collection-lists.js: every obtainable collectable, for the Time Memoria
collections import. Run daily by .github/workflows/collection-lists.yml.

Sources (checked against the game sheets 18 Oct 2026):
  * FFXIV Collect's public API. Its ids are the game's own sheet rows for mounts,
    minions, orchestrion, Triple Triad cards, emotes and fashion accessories, and
    the NPC's own id for Triple Triad NPCs. So the plugin's owned ids look up here
    directly. Collect lists only obtainable items, which is the filter the raw
    sheets lack, and it carries the patch and how to get each one.
  * XIVAPI for facewear. Collect numbers facewear its own way, but its names
    match the game's GlassesStyle sheet exactly, and the plugin sends style ids.
    XIVAPI serves that sheet, so the join needs no game install.

The file is rewritten only when a list changes, so a quiet day makes no commit.
A failed fetch exits non-zero and leaves the last good file in place.

Usage: python tools/build_collection_lists.py [output path]
"""
import datetime
import json
import re
import sys
import urllib.request

OUTPUT = sys.argv[1] if len(sys.argv) > 1 else "collection-lists.js"
AGENT = "LegendMemoria-Ledger/1.0 (+https://legendmemoria.org)"

# export key -> Collect endpoint. Keys match the plugin's collections export.
COLLECT = {
    "mounts": "mounts",
    "minions": "minions",
    "orchestrion": "orchestrions",
    "ttCards": "triad/cards",
    "ttNpcs": "triad/npcs",
    "emotes": "emotes",
    "accessories": "fashions",
    "facewear": "facewear",
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def patch_key(patch):
    """'3.55a' -> (3, 55, 'a'); sorts patches as versions, not decimals."""
    match = re.match(r"(\d+)\.(\d+)([a-z]?)", patch or "0.0")
    return (int(match.group(1)), int(match.group(2).ljust(2, "0")), match.group(3))


def source_of(entry):
    sources = entry.get("sources") or []
    if not sources:
        return ["", ""]
    return [sources[0].get("type") or "", sources[0].get("text") or ""]


def build():
    styles = fetch("https://v2.xivapi.com/api/sheet/GlassesStyle?fields=Name&limit=1000")["rows"]
    style_by_name = {row["fields"]["Name"].lower(): row["row_id"] for row in styles if row["fields"].get("Name")}

    lists = {}
    for key, endpoint in COLLECT.items():
        results = fetch(f"https://ffxivcollect.com/api/{endpoint}")["results"]
        rows = []
        for entry in results:
            row_id = entry["id"]
            if key == "facewear":
                row_id = style_by_name.get(entry["name"].lower())
                if row_id is None:
                    print(f"facewear: no game style named {entry['name']!r}; left out", file=sys.stderr)
                    continue
            rows.append([row_id, entry["name"], entry.get("patch") or ""] + source_of(entry))
        rows.sort(key=lambda r: (patch_key(r[2]), r[1].lower(), r[0]))
        lists[key] = rows
        print(f"{key}: {len(rows)}")

    if not lists["mounts"] or not lists["minions"]:
        raise SystemExit("A core list came back empty; keeping the last good file.")
    return lists


def previous_lists():
    try:
        text = open(OUTPUT, encoding="utf-8").read()
    except FileNotFoundError:
        return None
    match = re.search(r"const COLLECTION_LISTS = (\{.*\});", text, re.S)
    return json.loads(match.group(1))["lists"] if match else None


def main():
    lists = build()
    if previous_lists() == lists:
        print("No change.")
        return

    latest = max((r[2] for rows in lists.values() for r in rows if r[2]), key=patch_key)
    payload = {
        "built": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d"),
        "latestPatch": latest,
        "lists": lists,
    }
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/build_collection_lists.py from FFXIV Collect and XIVAPI. Do not edit.\n")
        out.write("// lists.<key>: [id, name, patch, source type, source]. Keys match Time Memoria's collections export.\n")
        out.write("const COLLECTION_LISTS = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"Wrote {OUTPUT}: latest patch {latest}.")


if __name__ == "__main__":
    main()
